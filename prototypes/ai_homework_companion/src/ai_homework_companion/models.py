"""Data models for the AI Homework Companion.

Same "one noun, one class" habit from `python_course/module_07_oop`, aimed
at exam-style practice instead of a student sitting an exam. A
`PracticeQuestion` bundles a command word, its mark allocation, and the
question text together — like one line of an exam paper. A `PracticeSet`
bundles a title, a case study, and a list of `PracticeQuestion`s together —
like the whole paper: cover, source material, questions.

`total_marks()` reads like a mark scheme's own summary line: it doesn't
store the total as another field that could drift out of sync with the
questions (imagine adding a question and forgetting to update a separate
`total` field) — it *computes* the total from the current questions every
time it's called, the same way a teacher adds up the marks column rather
than trusting a number written at the top from an earlier draft.

These sets are generated by a Claude agent following
`prompts/generate_practice_set.md` and the matching `styles/*.md` board
guide, then marked later by the `ai_examiner` prototype's BLT rubric
thinking — this module only models the *shape* of a practice paper, it
doesn't generate or mark one.
"""

from dataclasses import dataclass


@dataclass
class PracticeQuestion:
    """One question on a practice paper, e.g.

    PracticeQuestion("Assess", 12, "Assess whether Green Grocers should
    expand online.") — a command word (what the student must DO, see the
    command-word ladder in each `styles/*.md` guide), how many marks it's
    worth, and the question text itself.
    """

    command_word: str
    marks: int
    text: str


@dataclass
class PracticeSet:
    """One practice paper: a title, a case study, and its questions.

    `title` names the fictional business the case study is built around
    (e.g. "Green Grocers Ltd"), `case_study` is the source material every
    question should be answerable from (plus real-world examples, but only
    for Edexcel IAL Unit 4 — see `styles/edexcel_ial_business.md`), and
    `questions` is the ordered list of `PracticeQuestion`s a student works
    through.
    """

    title: str
    case_study: str
    questions: list[PracticeQuestion]

    def total_marks(self) -> int:
        """Sum of every question's marks — recomputed, never stored twice."""
        return sum(question.marks for question in self.questions)
